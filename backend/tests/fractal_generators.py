"""
Generators for mathematical fractals with *known* dimensions.

Used by test_fractal.py to validate the box-counting implementation against ground truth:
    - Sierpinski triangle : D = log(3)/log(2) ~= 1.585
    - Sierpinski carpet   : D = log(8)/log(3) ~= 1.893
    - Koch curve          : D = log(4)/log(3) ~= 1.262

Proving the measure recovers these values is the correctness slide of the whole project.
"""
from __future__ import annotations

import numpy as np


def sierpinski_triangle(order: int = 7) -> np.ndarray:
    """Binary Sierpinski triangle via the bitwise-AND rule. D = log3/log2 ~= 1.585."""
    size = 2 ** order
    ys, xs = np.mgrid[0:size, 0:size]
    # A point is 'on' where (x & y) == 0 (Pascal-triangle mod 2 pattern).
    tri = ((xs & ys) == 0).astype(np.uint8)
    return tri


def sierpinski_carpet(order: int = 4) -> np.ndarray:
    """Binary Sierpinski carpet. D = log8/log3 ~= 1.893."""
    size = 3 ** order
    carpet = np.ones((size, size), dtype=np.uint8)

    def carve(x0: int, y0: int, s: int) -> None:
        if s < 3:
            return
        t = s // 3
        # Remove the central sub-square.
        carpet[y0 + t:y0 + 2 * t, x0 + t:x0 + 2 * t] = 0
        for i in range(3):
            for j in range(3):
                if i == 1 and j == 1:
                    continue
                carve(x0 + j * t, y0 + i * t, t)

    carve(0, 0, size)
    return carpet


def koch_curve(order: int = 5, size: int = 1024) -> np.ndarray:
    """
    Rasterised Koch curve on a `size`x`size` canvas. D = log4/log3 ~= 1.262.

    Generated by repeatedly replacing each segment with the 4-segment Koch generator,
    then drawing the polyline onto a binary grid.
    """
    # Start with a horizontal segment.
    p0 = np.array([0.05, 0.5])
    p1 = np.array([0.95, 0.5])
    points = [p0, p1]

    for _ in range(order):
        new_points = []
        for a, b in zip(points[:-1], points[1:]):
            a = np.asarray(a); b = np.asarray(b)
            delta = (b - a) / 3.0
            pa = a
            p_1 = a + delta
            p_2 = a + 2 * delta
            # Apex of the equilateral bump.
            mid = a + 1.5 * delta
            perp = np.array([-delta[1], delta[0]]) * np.sqrt(3)
            apex = mid + perp
            new_points.extend([pa, p_1, apex, p_2])
        new_points.append(points[-1])
        points = new_points

    canvas = np.zeros((size, size), dtype=np.uint8)
    pts = (np.asarray(points) * (size - 1)).astype(int)
    for a, b in zip(pts[:-1], pts[1:]):
        _draw_line(canvas, a[0], a[1], b[0], b[1])
    return canvas


def _draw_line(img: np.ndarray, x0: int, y0: int, x1: int, y1: int) -> None:
    """Bresenham line into a binary image (y is row)."""
    dx = abs(x1 - x0)
    dy = -abs(y1 - y0)
    sx = 1 if x0 < x1 else -1
    sy = 1 if y0 < y1 else -1
    err = dx + dy
    h, w = img.shape
    while True:
        if 0 <= y0 < h and 0 <= x0 < w:
            img[y0, x0] = 1
        if x0 == x1 and y0 == y1:
            break
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x0 += sx
        if e2 <= dx:
            err += dx
            y0 += sy
